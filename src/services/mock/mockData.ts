// ---- Helpers ----

function ts(offsetMinutes: number = 0): string {
  // All timestamps relative to a fixed "now" so data is deterministic
  const base = new Date('2026-09-07T10:00:00.000Z');
  base.setMinutes(base.getMinutes() - offsetMinutes);
  return base.toISOString();
}

function tsExact(isoString: string): string {
  return isoString;
}

