function makeDailyTimeSeries(days: number, baseValue: number, variance: number): { timestamp: string; value: number }[] {
  const result = [];
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date('2026-09-07');
    d.setDate(d.getDate() - i);
    // Deterministic "variance" using day-of-week
    const dayOfWeek = d.getDay();
    const multiplier = dayOfWeek === 0 || dayOfWeek === 6 ? 0.6 : 1.0;
    const v = Math.round((baseValue + (i % 7) * variance) * multiplier);
    result.push({ timestamp: d.toISOString().slice(0, 10), value: Math.max(0, v) });
  }
  return result;
}

